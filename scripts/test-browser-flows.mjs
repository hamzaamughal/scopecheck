import assert from 'node:assert/strict';
import { randomUUID, randomBytes } from 'node:crypto';
import { createRequire } from 'node:module';
import nextEnv from '@next/env';
import { Pool } from 'pg';
import { betterAuth } from 'better-auth';
import { createAuthOptions } from '../src/lib/auth-options.ts';
nextEnv.loadEnvConfig(process.cwd());
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base=process.env.BETTER_AUTH_URL || 'http://localhost:3000';
assert.ok(['localhost','127.0.0.1'].includes(new URL(base).hostname));
const pool=new Pool({connectionString:process.env.DATABASE_URL});
const email=`browser-qa-${randomUUID()}@example.com`, password=randomBytes(24).toString('base64url');
const mail=[];
const auth=betterAuth(createAuthOptions(pool,async m=>{mail.push(m);}));
let browser, userId;
try {
 const res=await auth.handler(new Request(base+'/api/auth/sign-up/email',{method:'POST',headers:{Origin:base,'Content-Type':'application/json'},body:JSON.stringify({name:'Browser QA',email,password})}));
 assert.equal(res.status,200);userId=(await res.json()).user.id;
 await auth.handler(new Request(mail[0].url));
 browser=await chromium.launch({channel:'msedge',headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 // Guard against any accidental paid generation while exploring UI.
 await context.route('**/api/projects/*/requests/*/assessment',async route=>{
  if(route.request().method()==='POST')throw new Error('Unexpected AI generation in browser test');
  await route.continue();
 });
 const page=await context.newPage();page.setDefaultTimeout(30000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 let failProjects=true;
 await context.route('**/api/projects',async route=>{
  if(route.request().method()==='GET' && failProjects){return route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({success:false,error:{code:'DATABASE_UNAVAILABLE',message:'Temporary failure for browser check.'}})});}
  await route.continue();
 });
 await page.goto(base+'/login');
 await page.getByLabel('Email',{exact:true}).fill(email);
 await page.getByLabel('Password',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Sign in',exact:true}).last().click();
 await page.getByRole('button',{name:'Try again',exact:true}).waitFor();
 failProjects=false;
 await page.getByRole('button',{name:'Try again',exact:true}).click();
 await page.getByRole('button',{name:'New project',exact:true}).waitFor();
 assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
 await page.getByRole('button',{name:'Toggle light and dark mode'}).click();
 assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
 await page.reload();await page.getByRole('button',{name:'New project',exact:true}).waitFor();
 assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
 await page.getByRole('button',{name:'New project',exact:true}).click();
 await page.locator('#project-name').fill('Browser QA website');
 await page.locator('#client-name').fill('QA Client');
 await page.locator('#project-scope').fill('Build five marketing pages. User accounts are excluded.');
 await page.getByRole('button',{name:'Create project',exact:true}).click();
 await page.getByRole('button',{name:'New request',exact:true}).click();
 await page.locator('#request-title').fill('Add login');
 await page.locator('#request-description').fill('Please add user accounts.');
 await page.getByRole('button',{name:'Add request',exact:true}).click();
 await context.route('**/api/usage',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({success:true,data:{usage:{limit:10,used:10,remaining:0,resetsAt:new Date(Date.now()+3600000).toISOString()}}})}));
 await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
 await page.getByRole('button',{name:'Daily limit reached',exact:true}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Daily limit reached',exact:true}).isDisabled(),true);
 await page.locator('#decision').selectOption('extra_work');
 await page.locator('#decision-note').fill('Outside the agreed scope.');
 await page.getByRole('button',{name:'Save decision',exact:true}).click();
 await page.getByRole('button',{name:'Update decision',exact:true}).waitFor();
 await page.reload();
 await page.locator('.project-card').filter({hasText:'Browser QA website'}).click();
 await page.locator('.request-row').filter({hasText:'Add login'}).click();
 assert.equal(await page.locator('#decision').inputValue(),'extra_work');
 assert.equal(await page.locator('#decision-note').inputValue(),'Outside the agreed scope.');
 await page.getByRole('button',{name:'All projects',exact:true}).first().click();
 await page.getByLabel('Search projects').fill('no-match-xyz');
 await page.getByText('No projects match this view.',{exact:false}).waitFor();
 await page.getByLabel('Search projects').fill('');
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Mobile horizontal overflow');
 await page.getByLabel('Your account').click();
 await page.getByRole('button',{name:'Sign out',exact:true}).click();
 await page.waitForURL('**/login');
 await page.goto(base+'/reset-password?error=INVALID_TOKEN');
 await page.getByText('This reset link is missing, expired, or already used.').waitFor();
 const resetResponse=await auth.handler(new Request(base+'/api/auth/request-password-reset',{method:'POST',headers:{Origin:base,'Content-Type':'application/json'},body:JSON.stringify({email,redirectTo:'/reset-password'})}));
 assert.equal(resetResponse.status,200);
 const reset=mail.find(m=>m.kind==='reset');assert.ok(reset);
 await page.goto(reset.url);
 const changedPassword=randomBytes(24).toString('base64url');
 await page.locator('#new-password').fill(changedPassword);
 await page.locator('#confirm-password').fill('does-not-match');
 await page.getByRole('button',{name:'Save new password'}).click();
 await page.getByRole('alert').filter({hasText:/passwords don.*match/}).waitFor();
 await page.locator('#confirm-password').fill(changedPassword);
 await page.getByRole('button',{name:'Save new password'}).click();
 await page.waitForURL('**/login?reset=1');
 await page.getByLabel('Email',{exact:true}).fill(email);
 await page.getByLabel('Password',{exact:true}).fill(changedPassword);
 await page.getByRole('button',{name:'Sign in',exact:true}).last().click();
 await page.getByRole('button',{name:'New project',exact:true}).waitFor();
 console.log('PASS: failed workspace load retry, quota blocks AI but allows manual decisions, reset form mismatch and successful new-password login.');
 assert.equal(errors.length,0,'Browser runtime errors: '+errors.join(';'));
 console.log('PASS: browser login, dark default, theme persistence, project/request creation, decision persistence, search, mobile width, logout, invalid reset link. No AI or email calls.');
} finally {
 if(browser)await browser.close();
 if(userId){
  await pool.query('DELETE FROM assessments WHERE request_id IN (SELECT r.id FROM requests r JOIN projects p ON p.id=r.project_id WHERE p.owner_user_id=$1)',[userId]);
  await pool.query('DELETE FROM requests WHERE project_id IN (SELECT id FROM projects WHERE owner_user_id=$1)',[userId]);
  await pool.query('DELETE FROM projects WHERE owner_user_id=$1',[userId]);
  await pool.query('DELETE FROM auth_user WHERE id=$1',[userId]);
 }
 await pool.end();
}
